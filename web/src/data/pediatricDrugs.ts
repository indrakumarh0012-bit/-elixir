/**
 * Pediatric drug schema for Smart-Elixir dosage calculator.
 * Seed list represents structure for a larger 200+ formulary.
 * Clinical use: decision support only — verify with local protocol.
 */

export interface PediatricDrug {
  id: string;
  name: string;
  category: string;
  recommendedDose: string;
  /** Baseline mg/kg/day for calculator default */
  defaultDoseMgPerKg: number;
  maxDosePerDayMg: number;
  frequencyOptions: string[];
  /** Default frequency label from frequencyOptions */
  defaultFrequency: string;
  /** How many doses per day for the default frequency */
  defaultDosesPerDay: number;
  route: string[];
  cautionsAndContraindications: string[];
  instructions: string;
  referenceSource: string;
  renalAdjustment: boolean;
}

/** Map common frequency labels → divisions per day */
export function dosesPerDayFromFrequency(freq: string): number {
  const map: Record<string, number> = {
    q4h: 6,
    q6h: 4,
    q8h: 3,
    q12h: 2,
    q24h: 1,
    OD: 1,
    BD: 2,
    TDS: 3,
    QID: 4,
  };
  return map[freq] ?? 1;
}

